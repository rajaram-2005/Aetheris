_FALLBACK: Final[str] = "11111/10001/10001/10001/10001/10001/11111"


def _compile(spec: str) -> tuple[tuple[int, ...], ...]:
    """Turn a ``0``/``1`` row spec into nested tuples of pixel flags."""
    rows = spec.split("/")
    return tuple(tuple(1 if c == "1" else 0 for c in row) for row in rows)


FONT: Final[dict[str, tuple[tuple[int, ...], ...]]] = {
    char: _compile(spec) for char, spec in _RAW.items()
}
FALLBACK_GLYPH: Final[tuple[tuple[int, ...], ...]] = _compile(_FALLBACK)


def glyph(char: str) -> tuple[tuple[int, ...], ...]:
    """Return the bitmap for ``char``, or the fallback box if unsupported."""
    return FONT.get(char, FALLBACK_GLYPH)


def text_width(text: str, scale: int = 1, tracking: int = 1) -> int:
    """Pixel width of ``text`` at the given scale and inter-glyph tracking."""
    if not text:
        return 0
    per = (GLYPH_WIDTH + tracking) * scale
    return per * len(text) - tracking * scale


def text_height(scale: int = 1) -> int:
    """Pixel height of a single line of text at ``scale``."""
    return GLYPH_HEIGHT * scale


